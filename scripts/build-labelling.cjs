'use strict';
// Writes labelling/tasks.js from the two natural manifests. Prints counts only. No planted info, no model output.
const fs = require('fs');
const path = require('path');
const { canonical, sha256, textHash } = require('../src/hash.cjs');
const { mulberry32, shuffle } = require('../src/prng.cjs');
const ROOT = path.join(__dirname, '..');
const SEED = 20250103;
function build(manifests) {
  const splits = {}, order = {};
  for (const [name, recs] of Object.entries(manifests)) {
    const sorted = [...recs].sort((a, b) => (a.id < b.id ? -1 : 1));
    splits[name] = sorted.map((r) => ({ id: r.id, title: r.title, image: r.image, attributes: r.attributes }));
    order[name] = shuffle(sorted.map((r) => r.id), mulberry32(SEED));
  }
  const body = { schema: 'listing-mismatch-tasks/v1', splits, order };
  return { ...body, tasksHash: sha256(canonical(body)) };
}
function render(tasks) { return '/* GENERATED by scripts/build-labelling.cjs. Do not edit. */\nwindow.LISTING_TASKS = ' + JSON.stringify(tasks) + ';\n'; }
if (require.main === module) {
  const read = (rel) => JSON.parse(fs.readFileSync(path.join(ROOT, rel), 'utf8'));
  const tasks = build({ 'natural-dev': read('data/splits/natural-dev.json'), 'natural-heldout': read('data/heldout/natural-heldout.json') });
  fs.writeFileSync(path.join(ROOT, 'labelling', 'tasks.js'), render(tasks));
  console.log(`build-labelling: natural-dev ${tasks.splits['natural-dev'].length}, natural-heldout ${tasks.splits['natural-heldout'].length}, tasksHash ${tasks.tasksHash}`);
  void textHash;
}
module.exports = { build, render };