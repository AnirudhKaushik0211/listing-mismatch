'use strict';
// Writes src/core/template.generated.js and demo/core.bundle.js (SPEC 2.3). Deterministic output.
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');
const ORDER = ['sha256.js', 'template.generated.js', 'prompt.js', 'parse.js', 'verdict.js', 'gemini-request.js', 'live-input.js'];
function pinnedModel() {
  try {
    const f = JSON.parse(fs.readFileSync(path.join(ROOT, 'eval', 'freeze.json'), 'utf8'));
    return (f.stages && f.stages.method && f.stages.method.model) || null;
  } catch (e) { return null; }
}
function build() {
  const tpl = fs.readFileSync(path.join(ROOT, 'src', 'prompts', 'check-v1.txt'), 'utf8').replace(/\r\n/g, '\n');
  const gen = '/* GENERATED by scripts/build-core.cjs from src/prompts/check-v1.txt. Do not edit. */\n' +
    '(function (root, factory) {\n  var api = factory();\n  if (typeof module === \'object\' && module.exports) module.exports = api;\n' +
    '  else { root.ListingCore = root.ListingCore || {}; for (var k in api) root.ListingCore[k] = api[k]; }\n' +
    '})(typeof window !== \'undefined\' ? window : globalThis, function () {\n  return { TEMPLATE: ' + JSON.stringify(tpl) + ' };\n});\n';
  const files = { 'src/core/template.generated.js': gen };
  let bundle = '/* GENERATED by scripts/build-core.cjs from src/core/*.js. Do not edit. */\n';
  for (const n of ORDER) {
    const text = n === 'template.generated.js' ? gen : fs.readFileSync(path.join(ROOT, 'src', 'core', n), 'utf8').replace(/\r\n/g, '\n');
    bundle += '\n/* ---- ' + n + ' ---- */\n' + text;
  }
  bundle += '\n(function (root) { root.ListingCore = root.ListingCore || {}; root.ListingCore.PINNED_MODEL = ' + JSON.stringify(pinnedModel()) + '; })(typeof window !== \'undefined\' ? window : globalThis);\n';
  files['demo/core.bundle.js'] = bundle;
  return files;
}
if (require.main === module) {
  const files = build();
  for (const [rel, text] of Object.entries(files)) fs.writeFileSync(path.join(ROOT, rel), text);
  console.log('build-core: wrote ' + Object.keys(files).join(', '));
}
module.exports = { build };